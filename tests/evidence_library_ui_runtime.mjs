import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('app/evidence_library_ui.py','utf8').match(/<script>\n([\s\S]*?)<\/script>/)[1];
const nodes=new Map();
const el=id=>{if(!nodes.has(id))nodes.set(id,{id,value:'',innerHTML:'',textContent:'',disabled:false,hidden:false,listeners:{},replaceChildren(){this.innerHTML='';},addEventListener(name,fn){this.listeners[name]=fn;},reset(){for(const x of nodes.values())x.value='';}});return nodes.get(id);};
const requests=[];
const context={document:{getElementById:el},URLSearchParams,fetch(url){return new Promise(resolve=>requests.push({url,resolve}));}};
vm.runInNewContext(source,context);
assert.equal(requests.length,1);
el('librarySearch').value='new filter';el('libraryFilters').listeners.input();
requests[0].resolve({ok:true,json:async()=>({items:[],total:100,next_cursor:'["old","cursor"]',scopes:[],device_coverage:'old'})});
await new Promise(setImmediate);
assert.equal(el('libraryNext').disabled,true,'Old response must not enable paging for draft filters');
assert.match(el('libraryStatus').textContent,/Filters changed/);
assert.equal(el('libraryRows').innerHTML,'');
el('libraryFilters').onsubmit({preventDefault(){}});
assert.match(requests[1].url,/q=new\+filter/);
assert.equal(new URL('http://test'+requests[1].url).searchParams.get('after'),'');
requests[1].resolve({ok:true,json:async()=>({items:[],total:0,next_cursor:'',scopes:[],device_coverage:'current'})});
await new Promise(setImmediate);
assert.match(el('libraryStatus').textContent,/0 matching/);
assert.equal(el('libraryNext').disabled,true);
console.log('Evidence Library deferred filter response and paging checks passed');
